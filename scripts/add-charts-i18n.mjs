// ── Merge ────────────────────────────────────────────────────────────────────

function merge(path, patch) {
  const json = JSON.parse(readFileSync(path, "utf8"));
  // nav keys
  json.nav = json.nav ?? {};
  if (!json.nav.chartBuilder) {
    json.nav.chartBuilder =
      patch === chartsBuilderEn ? "Chart builder" : "Concepteur de graphiques";
  }
  if (!json.nav.chartBuilderDesc) {
    json.nav.chartBuilderDesc =
      patch === chartsBuilderEn
        ? "Custom charts from your trades"
        : "Graphiques personnalisés depuis vos trades";
  }
  // analytics deep link
  json.analytics = json.analytics ?? {};
  if (!json.analytics.openChartBuilder) {
    json.analytics.openChartBuilder =
      patch === chartsBuilderEn ? "Chart builder" : "Concepteur de graphiques";
  }
  // chartsBuilder namespace (deep merge for later phases)
  json.chartsBuilder = {
    ...(json.chartsBuilder ?? {}),
    ...patch,
    filters: { ...(json.chartsBuilder?.filters ?? {}), ...patch.filters },
    config: { ...(json.chartsBuilder?.config ?? {}), ...patch.config },
    dimensions: { ...(json.chartsBuilder?.dimensions ?? {}), ...patch.dimensions },
    measures: { ...(json.chartsBuilder?.measures ?? {}), ...patch.measures },
    buckets: { ...(json.chartsBuilder?.buckets ?? {}), ...patch.buckets },
    warnings: { ...(json.chartsBuilder?.warnings ?? {}), ...patch.warnings },
    preview: { ...(json.chartsBuilder?.preview ?? {}), ...patch.preview },
    saved: { ...(json.chartsBuilder?.saved ?? {}), ...patch.saved },
    toast: { ...(json.chartsBuilder?.toast ?? {}), ...patch.toast },
    errors: { ...(json.chartsBuilder?.errors ?? {}), ...patch.errors },
  };
  writeFileSync(path, JSON.stringify(json, null, 2) + "\n");
  console.log(`✓ merged ${path}`);
}

